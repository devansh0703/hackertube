package com.github.hackertube.api.obj

import android.os.Parcelable
import com.github.hackertube.db.obj.DownloadItem
import com.github.hackertube.enums.FileType
import kotlinx.parcelize.Parcelize
import kotlinx.serialization.Serializable
import kotlin.io.path.Path

@Serializable
@Parcelize
data class Subtitle(
    val url: String? = null,
    val mimeType: String? = null,
    val name: String? = null,
    val code: String? = null,
    val autoGenerated: Boolean? = null
): Parcelable {
    fun toDownloadItem(videoId: String) = DownloadItem(
        type = FileType.SUBTITLE,
        videoId = videoId,
        fileName = "${videoId}_${code}.srt",
        path = Path(""),
        language = code
    )
}
